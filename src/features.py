"""Feature building shared by evaluation, back-tests, forecasting and the dashboard pipeline.

build_features() is the v1 logic generated by make_stage5.py (same as notebooks/03_model.ipynb), unchanged.
build_features_v2() = v1 + days_since_holiday + sales_lag_364 (kept after the back-test experiment, A4).
add_v3_features() = candidate holiday + promotion features for the accuracy experiments (6i, src/tune.py).
Every past-sales clue is at least H = 14 days old.
"""
import re

import numpy as np
import pandas as pd

H = 14
WEATHER_COLS = ["rain_mm", "temp_max", "rainy_day"]
FEATURES = [
    "store_id", "family", "city", "store_type", "cluster", "is_perishable",
    "dayofweek", "day", "month", "weekofyear", "dayofyear", "is_payday",
    "is_holiday", "is_national_holiday", "is_regional_holiday", "is_local_holiday", "is_event", "is_quake",
    "days_to_holiday", "onpromotion",
    "lag_14", "lag_21", "lag_28", "lag_35", "lag_42", "mean_7", "mean_28", "mean_56", "std_28",
    "trans_lag14", "oil_lag14", "rain_mm", "temp_max", "rainy_day",
]


def build_features(df, weather):
    # df: clean table with never_sold pairs removed. weather: date, city, rain_mm, temp_max
    df = df.copy()
    df["family"] = df["family"].astype(str)
    df = df.merge(weather, on=["date", "city"], how="left")
    df["rain_mm"] = df["rain_mm"].fillna(0)
    df["temp_max"] = df.groupby("city")["temp_max"].transform(lambda s: s.ffill().bfill())
    df["rainy_day"] = (df.rain_mm >= 5).astype(int)

    df["dayofweek"] = df.date.dt.dayofweek
    df["day"] = df.date.dt.day
    df["month"] = df.date.dt.month
    df["weekofyear"] = df.date.dt.isocalendar().week.astype(int)
    df["dayofyear"] = df.date.dt.dayofyear

    hol_dates = pd.DatetimeIndex(sorted(df.loc[df.is_national_holiday == 1, "date"].unique()))
    cal = pd.DataFrame({"date": pd.date_range(df.date.min(), df.date.max())})
    pos = hol_dates.searchsorted(cal.date)
    nxt = pd.Series(list(hol_dates) + [pd.NaT])[pos].to_numpy()
    cal["days_to_holiday"] = (nxt - cal.date.to_numpy()) / np.timedelta64(1, "D")
    cal["days_to_holiday"] = cal["days_to_holiday"].fillna(60).clip(upper=60)
    oil = df.groupby("date")["dcoilwtico"].first().reindex(cal.date).ffill()
    cal["oil_lag14"] = oil.shift(H).to_numpy()
    df = df.merge(cal, on="date", how="left")

    df = df.sort_values(["store_nbr", "family", "date"]).reset_index(drop=True)
    df["sales_open"] = df.sales.where(df.is_closed == 0)
    keys = [df.store_nbr, df.family]
    g = df.groupby(keys)["sales_open"]
    for lag in [14, 21, 28, 35, 42]:
        df[f"lag_{lag}"] = g.shift(lag)
    old = g.shift(H)
    for w in [7, 28, 56]:
        df[f"mean_{w}"] = old.groupby(keys).transform(lambda s: s.rolling(w, min_periods=1).mean())
    df["std_28"] = old.groupby(keys).transform(lambda s: s.rolling(28, min_periods=7).std())

    tr = df.groupby(["store_nbr", "date"])["transactions"].first().groupby(level=0).shift(H).rename("trans_lag14")
    df = df.merge(tr.reset_index(), on=["store_nbr", "date"], how="left")

    for c in ["family", "city", "store_type"]:
        df[c] = df[c].astype("category")
    df["store_id"] = df.store_nbr.astype("category")
    return df


V2_EXTRA = ["days_since_holiday", "sales_lag_364"]


def add_v2_features(df):
    # days_since_holiday: days since the last national holiday (0 on the day itself), capped at 60.
    # sales_lag_364: same weekday about one year earlier (364 days, so still >= 14 days old).
    nat = pd.DatetimeIndex(sorted(df.loc[df.is_national_holiday == 1, "date"].unique()))
    cal = pd.DataFrame({"date": pd.date_range(df.date.min(), df.date.max())})
    pos = nat.searchsorted(cal.date, side="right") - 1
    prev = pd.Series(list(nat) + [pd.NaT])[np.where(pos >= 0, pos, len(nat))].to_numpy()
    cal["days_since_holiday"] = (cal.date.to_numpy() - prev) / np.timedelta64(1, "D")
    cal["days_since_holiday"] = cal["days_since_holiday"].fillna(60).clip(upper=60)
    df = df.drop(columns=["days_since_holiday"], errors="ignore").merge(cal, on="date", how="left")
    df = df.sort_values(["store_nbr", "family", "date"]).reset_index(drop=True)
    df["sales_lag_364"] = df.groupby(["store_nbr", "family"], observed=True)["sales_open"].shift(364)
    return df


def build_features_v2(df, weather):
    return add_v2_features(build_features(df, weather))


# Accuracy experiments (6i, src/tune.py): candidate holiday and promotion features
HOLIDAY_EXTRA = ["hol_type", "long_weekend", "days_to_day_off", "days_since_day_off", "near_holiday"]
PROMO_EXTRA = ["promo_vs_recent"]
HOL_TYPES = {"Holiday": 1, "Transfer": 2, "Bridge": 3, "Additional": 4}   # national kinds; "Work Day" dropped
DAY_OFF = [1, 2, 3]                                                       # Holiday, Transfer, Bridge = real days off
NEAR_DAYS = 14


def holiday_name(desc):
    # "Traslado Batalla de Pichincha", "Puente Dia de Difuntos", "Navidad-4" -> base holiday name
    return re.sub(r"[+-]\d+$", "", re.sub(r"^(Traslado|Puente) ", "", desc)).strip()


def national_calendar(holidays, dates):
    # One row per day. Same cleaning rules as notebooks/01_cleaning.ipynb: transferred=True and "Work Day"
    # dropped; national, non-event rows only. Holidays are known in advance, so no 14-day rule is needed.
    h = holidays[(~holidays.transferred) & (holidays.locale == "National") & holidays.type.isin(list(HOL_TYPES))]
    h = h.assign(code=h.type.map(HOL_TYPES), name=h.description.map(holiday_name))
    names = sorted(h.name.unique()) + ["none"]
    h = h.sort_values(["date", "code"]).drop_duplicates("date")
    cal = pd.DataFrame({"date": dates}).merge(h[["date", "code", "name"]], on="date", how="left")
    cal["hol_type"] = cal.code.fillna(0).astype(int)
    # long weekend: 3+ days in a row that are Saturday, Sunday or a real day off
    free = cal.hol_type.isin(DAY_OFF) | (cal.date.dt.dayofweek >= 5)
    run = (free != free.shift()).cumsum()
    cal["long_weekend"] = (free & (free.groupby(run).transform("size") >= 3)).astype(int)
    off = pd.DatetimeIndex(cal.date[cal.hol_type.isin(DAY_OFF)])
    cal["days_to_day_off"], cal["days_since_day_off"] = gaps(off, cal.date)
    # nearest national holiday (any kind) within 14 days, ties -> the coming one
    hol = pd.DatetimeIndex(h.date)
    to_next, since_prev = gaps(hol, cal.date, cap=None)
    use_next = to_next.fillna(np.inf) <= since_prev.fillna(np.inf)
    name = h.set_index("date").name
    nxt = cal.date + pd.to_timedelta(to_next, unit="D")
    prv = cal.date - pd.to_timedelta(since_prev, unit="D")
    near = np.where(use_next, nxt.map(name), prv.map(name))
    dist = np.where(use_next, to_next, since_prev)
    cal["near_holiday"] = pd.Categorical(np.where(dist <= NEAR_DAYS, near, "none"), categories=names)
    return cal[["date"] + HOLIDAY_EXTRA]


def gaps(days, dates, cap=60):
    # days until the next / since the last date in `days` (0 on the day itself), capped
    days = days.sort_values()
    pos = days.searchsorted(dates)
    nxt = pd.Series(list(days) + [pd.NaT])[pos].to_numpy()
    pos = days.searchsorted(dates, side="right") - 1
    prv = pd.Series(list(days) + [pd.NaT])[np.where(pos >= 0, pos, len(days))].to_numpy()
    to_next = pd.Series((nxt - dates.to_numpy()) / np.timedelta64(1, "D"))
    since = pd.Series((dates.to_numpy() - prv) / np.timedelta64(1, "D"))
    if cap is None:
        return to_next, since
    return to_next.fillna(cap).clip(upper=cap), since.fillna(cap).clip(upper=cap)


def add_v3_features(df, holidays):
    # Holiday calendar runs to the end of the holiday file, so days near the data end still see coming holidays
    dates = pd.date_range(df.date.min(), max(df.date.max(), holidays.date.max()))
    df = df.drop(columns=HOLIDAY_EXTRA + PROMO_EXTRA, errors="ignore").merge(national_calendar(holidays, dates),
                                                                            on="date", how="left")
    df = df.sort_values(["store_nbr", "family", "date"]).reset_index(drop=True)
    # promo_vs_recent: planned promotions today minus the usual level in the mean_28 window (14+ days old)
    keys = [df.store_nbr, df.family]
    old = df.groupby(keys, observed=True)["onpromotion"].shift(H)
    usual = old.groupby(keys, observed=True).transform(lambda s: s.rolling(28, min_periods=1).mean())
    df["promo_vs_recent"] = df.onpromotion - usual
    return df


def mae(y, p):
    return float(np.mean(np.abs(np.asarray(y) - np.asarray(p))))


def wape(y, p):
    y, p = np.asarray(y), np.asarray(p)
    return float(np.sum(np.abs(y - p)) / np.sum(y) * 100) if np.sum(y) > 0 else float("nan")
