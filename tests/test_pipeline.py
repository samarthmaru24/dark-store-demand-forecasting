SAME_DAY = {"sales", "sales_open", "dcoilwtico", "transactions"}


@pytest.fixture(scope="session")
def table():
    return model.feature_table()


def lookup(df, col, days):
    # value of `col` for the same store x category `days` earlier
    prev = df[["store_nbr", "family", "date", col]].copy()
    prev["date"] = prev["date"] + pd.Timedelta(days=days)
    return prev.rename(columns={col: "prev"})


@pytest.mark.parametrize("feature,col,days", [("lag_14", "sales_open", 14), ("sales_lag_364", "sales_open", 364)])
def test_sales_lags_are_old_enough(table, feature, col, days):
    sample = table[table[feature].notna()].sample(1000, random_state=0)
    m = sample.merge(lookup(table, col, days), on=["store_nbr", "family", "date"], how="left")
    assert len(m) == 1000 and np.allclose(m[feature], m.prev)


def test_transactions_and_oil_are_14_days_old(table):
    sample = table[table.trans_lag14.notna()].sample(1000, random_state=1)
    m = sample.merge(lookup(table, "transactions", 14), on=["store_nbr", "family", "date"], how="left")
    assert np.allclose(m.trans_lag14, m.prev)
    oil = table.groupby("date")["dcoilwtico"].first()
    days = table.loc[table.oil_lag14.notna(), ["date", "oil_lag14"]].drop_duplicates("date").sample(200, random_state=2)
    assert np.allclose(days.oil_lag14, oil.reindex(days.date - pd.Timedelta(days=14)).to_numpy())


