def test_splits_do_not_overlap(table):
    assert model.TRAIN_START < model.VALID_START < model.TEST_START
    info = model.final_info()
    assert info["horizon_days"] == 14
    for s in model.BACKTEST_STARTS:
        train, part = model.window(table, s)
        assert train.date.max() < s <= part.date.min()
        assert part.date.max() < model.TEST_START          # back-tests never touch the locked test days
    train, test = model.window(table, model.TEST_START)
    assert train.date.max() < model.TEST_START and test.date.max() == pd.Timestamp("2017-08-15")


def test_forecast_and_plan_outputs_are_valid():
    fc = pd.read_parquet(ROOT / "reports" / "forecast_next14.parquet")
    cols = ["forecast", "forecast_low", "forecast_high"]
    assert fc[cols].notna().all().all() and (fc[cols] >= 0).all().all()
    assert (fc.forecast_low <= fc.forecast).all() and (fc.forecast <= fc.forecast_high).all()
    assert fc.date.min() == pd.Timestamp("2017-08-16") and fc.date.nunique() == 14
    plan = pd.read_parquet(ROOT / "reports" / "reorder_plan.parquet")
    num = ["forecast_window", "buffer", "stock_SIMULATED", "order_qty"]
    assert plan[num].notna().all().all() and (plan[num] >= 0).all().all()
    assert set(plan.status) <= {"Urgent", "Reorder", "OK"}
    assert len(plan) == fc.groupby(["store_nbr", "family"]).ngroups


def test_reorder_maths_on_hand_made_example():
    dates = pd.date_range("2017-08-16", periods=14)
    spec = {  # family: (is_perishable, forecast/day, forecast_high/day, stock)
        "P": (1, 10.0, 12.0, 20), "L": (0, 5.0, 20.0, 200), "T": (0, 0.5, 0.5, 0), "U": (1, 10.0, 10.0, 5)}
    fc = pd.DataFrame([{"date": d, "store_nbr": 1, "family": f, "is_perishable": p, "forecast": v, "forecast_high": h}
                       for f, (p, v, h, _) in spec.items() for d in dates])
    stock = pd.DataFrame([{"store_nbr": 1, "family": f, "stock_SIMULATED": s} for f, (*_, s) in spec.items()])
    plan = reorder.build_plan(fc, stock, tiny_families=["T"]).set_index("family")
    # P: window 3 -> 30 units, buffer = 3 x 2 = 6, order = 30 + 6 - 20 = 16, cover = 20/10 = 2.0 -> not Urgent
    assert tuple(plan.loc["P", ["forecast_window", "buffer", "order_qty", "days_of_cover"]]) == (30, 6, 16, 2.0)
    assert plan.loc["P", "status"] == "Reorder"
    # L: window 14 -> 70, spread 210 capped at 50% = 35, order = max(0, 70 + 35 - 200) = 0 -> OK
    assert tuple(plan.loc["L", ["forecast_window", "buffer", "order_qty"]]) == (70, 35, 0) and plan.loc["L", "status"] == "OK"
    # T: tiny -> buffer at least 1, order = ceil(7 + 1 - 0) = 8; 0 days of cover but < 1 unit/day -> never Urgent
    assert tuple(plan.loc["T", ["buffer", "order_qty"]]) == (1, 8) and plan.loc["T", "status"] == "Reorder"
    # U: cover = 5/10 = 0.5 days -> Urgent, order = 30 + 0 - 5 = 25
    assert plan.loc["U", "order_qty"] == 25 and plan.loc["U", "status"] == "Urgent"


